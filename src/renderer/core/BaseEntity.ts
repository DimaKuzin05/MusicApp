// Абстрактный класс
// [Требование] Все пользовательские сущности наследуются от абстрактного класса

export abstract class BaseEntity {
    protected _id: number;

    constructor(id: number) {
        this._id = id;
    }

    /** Краткое описание объекта — обязан реализовать наследник */
    abstract getSummary(): string;

    /** Сравнение с другой сущностью — для сортировки */
    abstract compareTo(other: BaseEntity): number;
}
